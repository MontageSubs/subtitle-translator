export function languageDisplayName(code: LanguageCode, uiLocale: LocaleCode): string {
  const table = NAMES[uiLocale] || NAMES.en;
  if (table[code]) return table[code];
  const base = code.split("-")[0];
  if (table[base]) return table[base];
  return NAMES.en[code] || NAMES.en[base] || code;
}

export function allKnownLanguageCodes(): LanguageCode[] {
  return Object.keys(NAMES.en);
}

